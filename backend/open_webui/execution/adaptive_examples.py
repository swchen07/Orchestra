def select_flash(models, available):
    indexed = {m['id']: m for m in models}
    chosen = {}
    for family in FAMILIES:
        matches = [p for p in available if p['framework_id'] == family and not p.get('profile_id')
                   and indexed.get(p['model_id'], {}).get('execution', {}).get('model_id')
                   in {'deepseek-flash', 'deepseek-v4-flash'}]
        if not matches:
            raise HTTPException(422, f'Enable a DeepSeek V4 Flash participant for {FAMILIES[family]} in this Project first')
        chosen[family] = matches[0]
    return chosen


def matrix(chosen):
    jobs = []
    for case in cases():
        for family, name in FAMILIES.items():
            jobs.append({'case': case['id'], 'name': name + ' Flash · ' + case['name'],
                         'bindings': {r['id']: chosen[family]['id'] for r in definition()['roles']},
                         'executor_pool': [chosen[family]['id']]})
    jobs.append({'case': 'incremental', 'name': 'Mixed Flash · Incremental dispatch',
                 'bindings': {'controller': chosen['claude-code']['id'], 'reviewer': chosen['hermes']['id']},
                 'executor_pool': [chosen[f]['id'] for f in FAMILIES]})
    return jobs


def followup_prompt(case, run_id):
    # Identify the intended attempt without handing remembered values to the roles.
    return (case['followup'] + '\nAccepted initial-attempt memory anchor: ' + str(uuid.UUID(run_id))
            + '. Recall each role\'s own facts from this exact run, not the earliest failed/rejected attempt '
            'or the first entry in a newly allocated native session. Keep all earlier history available; '
            'cite the full host report references from the anchored run.')


async def run_suite(request, user, project, suite):
    from open_webui.execution.project_data import project_lock, update_overlay
    from open_webui.execution.workflows import generate_workflow
    from open_webui.models.chats import Chats

    async def persist():
        async with project_lock(project['id']):
            await update_overlay(project['id'], user, 'execution_example_suite', copy.deepcopy(suite))

    async def turn(job, prompt):
        chat = await Chats.get_chat_by_id(job['chat_id'])
        authorize_example_chat(chat, user.id, project['id'])
        history = copy.deepcopy(chat.chat['history'])
        parent = history.get('currentId')
        if not history.get('messages'):
            parent = None
        uid, aid = str(uuid.uuid4()), str(uuid.uuid4())
        now = int(time.time())
        if parent:
            history['messages'][parent].setdefault('childrenIds', []).append(uid)
        history['messages'][uid] = {'id': uid, 'role': 'user', 'parentId': parent, 'childrenIds': [aid],
                                    'content': prompt, 'timestamp': now, 'models': [job['model_id']]}
        history['messages'][aid] = {'id': aid, 'role': 'assistant', 'parentId': uid, 'childrenIds': [],
                                    'content': '', 'timestamp': now, 'model': job['model_id'],
                                    'modelName': 'Adaptive modules', 'done': False}
        history['currentId'] = aid
        if not await Chats.update_chat_by_id(chat.id, {'history': history}):
            raise HTTPException(500, 'Could not save the example chat turn')
        latest_status = None

        async def observe(record):
            nonlocal latest_status
            if latest_status == record['status']:
                return
            latest_status = record['status']
            status = {'action': 'workflow', 'done': record['status'] not in {'queued', 'running'},
                      'description': 'Adaptive modules · ' + record['status'],
                      'workflow': {'run_id': record['id'], 'name': 'Adaptive modules · Independent review'}}
            await Chats.upsert_message_to_chat_by_id_and_message_id(chat.id, aid, {'statusHistory': [status]}, touch=False)
            job['current_run_id'] = record['id']
            if record['status'] not in {'queued', 'running'}:
                job.setdefault('runs', []).append({'id': record['id'], 'status': record['status'],
                                                   'review': record.get('review', {}),
                                                   'budget': (record.get('control') or {}).get('budget')})
            await persist()

        body = {'model': job['model_id'], 'messages': [{'role': 'user', 'content': prompt}], 'stream': False,
                'metadata': {'chat_id': chat.id, 'user_message_id': uid, 'message_id': aid,
                             'execution_project': project, 'execution_workflow_id': suite['workflow_id'],
                             'execution_workflow_policy': 'automatic',
                             'execution_workflow_overrides': {'workflow_id': suite['workflow_id'],
                                                              'roles': {r: {'participant_id': p} for r, p in job['bindings'].items()},
                                                              **({'executor_pool': job['executor_pool']} if 'executor_pool' in job else {})}}}
        try:
            result = await generate_workflow(request, body, user, publish_observer=observe)
            await Chats.upsert_message_to_chat_by_id_and_message_id(chat.id, aid, {
                'content': result['choices'][0]['message']['content'], 'usage': result.get('usage'), 'done': True})
        except HTTPException as error:
            await Chats.upsert_message_to_chat_by_id_and_message_id(chat.id, aid, {
                'content': 'Run failed. Inspect the retained activity for details.',
                'error': {'content': str(error.detail)}, 'done': True})
            raise
        except asyncio.CancelledError:
            await Chats.upsert_message_to_chat_by_id_and_message_id(chat.id, aid, {
                'content': 'Example run stopped. Completed reports remain in Activity.', 'done': True,
                'error': {'content': 'Stopped'}})
            raise
        except Exception:
            await Chats.upsert_message_to_chat_by_id_and_message_id(chat.id, aid, {
                'content': 'Example execution failed. Retained activity is available for inspection.',
                'error': {'content': 'Example execution failed'}, 'done': True})
            raise

    try:
        # Sequential chats avoid contaminating the within-chat async timing with another test's queue.
        for job in suite['chats']:
            if job['status'] == 'completed':
                continue
            case = next(c for c in cases() if c['id'] == job['case'])
            job['status'] = 'running'; await persist()
            try:
                if job.get('phase') != 'followup':
                    job['phase'] = 'initial'
                    await turn(job, case['prompt'])
                    job['initial_run_id'] = job['current_run_id']
                if not job.get('initial_run_id'):
                    job['initial_run_id'] = next(r['id'] for r in job['runs']
                                                 if r['status'].startswith('completed')
                                                 and r.get('review', {}).get('status') == 'approved')
                job['phase'] = 'followup'
                await turn(job, followup_prompt(case, job['initial_run_id']))
                job['status'] = 'completed'
                job.pop('error', None)
            except Exception as error:
                job['status'] = 'failed'
                job['error'] = str(error.detail) if isinstance(error, HTTPException) else 'Example execution failed'
            await persist()
        suite['status'] = 'completed' if all(j['status'] == 'completed' for j in suite['chats']) else 'completed_with_errors'
    except asyncio.CancelledError:
        suite['status'] = 'interrupted'
        for job in suite['chats']:
            if job['status'] in {'queued', 'running'}:
                job['status'] = 'interrupted'
        raise
    finally:
        await persist()
        active_suites.pop(project['id'], None)
